internal fun translateKorean(english: String): String {
    koreanUiStrings[english]?.let { return it }
    for ((pattern, localized) in koreanDynamicPatterns) {
        val match = pattern.matchEntire(english) ?: continue
        var result = localized
        // Reverse order avoids altering capture placeholders inside inserted app names.
        for (i in match.groupValues.lastIndex downTo 1) {
            result = result.replace("{$i}", match.groupValues[i])
        }
        return result
    }
    return english
}
